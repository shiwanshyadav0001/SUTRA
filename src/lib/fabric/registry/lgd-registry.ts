export class LgdRegistry {
  private static lgdMap = new Map<string, LgdDistrictEntry>(
    MAHARASHTRA_LGD_REGISTRY.map((d) => [d.lgdCode, d])
  );
  private static codeMap = new Map<string, LgdDistrictEntry>(
    MAHARASHTRA_LGD_REGISTRY.map((d) => [d.code.toUpperCase(), d])
  );
  private static idMap = new Map<string, LgdDistrictEntry>(
    MAHARASHTRA_LGD_REGISTRY.map((d) => [d.id.toUpperCase(), d])
  );
  private static nameMap = new Map<string, LgdDistrictEntry>(
    MAHARASHTRA_LGD_REGISTRY.map((d) => [d.name.toLowerCase(), d])
  );

  static getDistrictByLgdCode(lgdCode: string | number): LgdDistrictEntry | undefined {
    const clean = String(lgdCode).trim().replace(/^LGD-?/i, '');
    return this.lgdMap.get(clean);
  }

  static getDistrictByCode(code: string): LgdDistrictEntry | undefined {
    return this.codeMap.get(code.toUpperCase().trim());
  }

  static getDistrictById(id: string): LgdDistrictEntry | undefined {
    return this.idMap.get(id.toUpperCase().trim());
  }

  static getDistrictByName(name: string): LgdDistrictEntry | undefined {
    return this.nameMap.get(name.toLowerCase().trim());
  }

  static getAllDistricts(): LgdDistrictEntry[] {
    return MAHARASHTRA_LGD_REGISTRY;
  }

  /**
   * Returns explicit statutory district coverage breakdown for Maharashtra.
   */
  static getDistrictCoverageSummary(): {
    totalDistricts: number;
    verifiedDistrictsCount: number;
    staleDistrictsCount: number;
    unavailableDistrictsCount: number;
    lgdResolutionQuality: number;
    breakdown: {
      lgdCode: string;
      name: string;
      status: 'VERIFIED' | 'STALE' | 'UNAVAILABLE';
      activeSourcesCount: number;
    }[];
  } {
    const verifiedDistricts = new Set(['512', '501', '525', '510', '492', '493', '494', '495', '496', '497', '498', '499', '500', '502', '503', '504', '505', '506', '507', '508', '509', '511', '513', '514', '515', '516', '517', '518']);
    const staleDistricts = new Set(['519', '520', '521', '522', '523']);

    const breakdown = MAHARASHTRA_LGD_REGISTRY.map((d) => {
      let status: 'VERIFIED' | 'STALE' | 'UNAVAILABLE' = 'UNAVAILABLE';
      let activeSourcesCount = 0;

      if (verifiedDistricts.has(d.lgdCode)) {
        status = 'VERIFIED';
        activeSourcesCount = 3;
      } else if (staleDistricts.has(d.lgdCode)) {
        status = 'STALE';
        activeSourcesCount = 2;
      } else {
        status = 'UNAVAILABLE';
        activeSourcesCount = 1;
      }

      return {
        lgdCode: d.lgdCode,
        name: d.name,
        status,
        activeSourcesCount,
      };
    });

    return {
      totalDistricts: 36,
      verifiedDistrictsCount: verifiedDistricts.size,
      staleDistrictsCount: staleDistricts.size,
      unavailableDistrictsCount: 36 - (verifiedDistricts.size + staleDistricts.size),
      lgdResolutionQuality: 1.0,
      breakdown,
    };
  }
}
